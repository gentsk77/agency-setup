#!/usr/bin/env python3
"""Validate the rulebook and regenerate the coverage report.

Checks every rule article in rules/ for the gradable-law format:
frontmatter fields, required sections, and explicit PASS/FAIL/UNCLEAR
grading conditions. Regenerates rules/coverage.md (generated file,
never hand-edited). Exits 1 on any violation so CI and pre-commit
hooks can gate on it. Stdlib only.
"""

import re
import sys
from pathlib import Path

RULES_DIR = Path(__file__).resolve().parent.parent / "rules"
COVERAGE = RULES_DIR / "coverage.md"
SKIP = {"README.md", "amendments.md", "coverage.md", "article-template.md"}
REQUIRED_FRONTMATTER = ["id", "title", "class", "kind", "status", "version", "adopted"]
REQUIRED_SECTIONS = ["## Statement", "## Grading", "## Evidence required"]
GRADING_MARKS = ["**PASS:**", "**FAIL:**", "**UNCLEAR:**"]


def parse_frontmatter(text: str) -> dict:
    match = re.match(r"\A---\s*\n(.*?)\n---\s*\n", text, re.DOTALL)
    if not match:
        return {}
    fields = {}
    for line in match.group(1).splitlines():
        if ":" in line:
            key, _, value = line.partition(":")
            fields[key.strip()] = value.strip()
    return fields


def validate(path: Path) -> tuple[dict, list[str]]:
    errors = []
    text = path.read_text(encoding="utf-8")
    front = parse_frontmatter(text)
    if not front:
        return {}, [f"{path.name}: missing frontmatter block"]
    for field in REQUIRED_FRONTMATTER:
        if field not in front or not front[field]:
            errors.append(f"{path.name}: frontmatter missing '{field}'")
    if front.get("status") == "active":
        for section in REQUIRED_SECTIONS:
            if section not in text:
                errors.append(f"{path.name}: missing section '{section}'")
        for mark in GRADING_MARKS:
            if mark not in text:
                errors.append(f"{path.name}: Grading lacks {mark} condition")
    return front, errors


def main() -> int:
    if not RULES_DIR.is_dir():
        print(f"rules directory not found: {RULES_DIR}")
        return 1
    articles = sorted(p for p in RULES_DIR.glob("*.md") if p.name not in SKIP)
    all_errors: list[str] = []
    rows = []
    seen_ids: dict[str, str] = {}
    for path in articles:
        front, errors = validate(path)
        all_errors.extend(errors)
        rule_id = front.get("id", "?")
        if rule_id in seen_ids:
            all_errors.append(f"{path.name}: duplicate id '{rule_id}' (also in {seen_ids[rule_id]})")
        else:
            seen_ids[rule_id] = path.name
        gradable = "yes" if front.get("status") == "active" and not errors else "no"
        rows.append((rule_id, front.get("title", "?"), front.get("status", "?"), gradable))

    lines = [
        "# Coverage report",
        "",
        "Generated by `scripts/validate_rules.py`. Never hand-edit.",
        "",
        "| id | title | status | gradable |",
        "|---|---|---|---|",
    ]
    lines += [f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} |" for r in rows]
    active = sum(1 for r in rows if r[2] == "active")
    lines += ["", f"Active rules: {active} of {len(rows)} articles."]
    COVERAGE.write_text("\n".join(lines) + "\n", encoding="utf-8")

    if all_errors:
        print("VALIDATION FAILED:")
        for error in all_errors:
            print(f"  - {error}")
        return 1
    print(f"OK: {len(rows)} articles, {active} active, coverage regenerated.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
